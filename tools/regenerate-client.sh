#!/usr/bin/env bash
#
# generate-client.sh — regenerate the Hugging Face Hub Go client with ogen.
#
# The upstream spec occasionally uses JSON Schema constructs ogen cannot parse
# (multi-type unions, scalar `items`, OpenAPI 3.1 numeric exclusive bounds,
# missing responses, colliding Go field names, ...). This script:
#
#   1. downloads the published spec,
#   2. normalizes scalar `items` values (true/false/null → {}) — recorded,
#   3. rewrites numeric exclusiveMinimum/Maximum to the 3.0 boolean form — recorded,
#   4. removes object properties whose schemas contain unsupported constructs,
#   5. removes properties that collide after ogen's Go name mangling — recorded,
#   6. removes whole operations that are invalid or still unsupported,
#   7. records every change in SPEC_DEVIATIONS.md,
#   8. verifies nothing unsupported remains, then runs ogen.
#
# Requirements:
#   - Go 1.25+
#   - go.mod with: go get -tool github.com/ogen-go/ogen@latest
#   - jq 1.5+ (module support via include/-L)
#
# jq filters live in ./jq/ as a module:
#   - bad.jq               — shared predicates (included by the others)
#   - report-props.jq     — find properties to remove
#   - report-items.jq     — find scalar `items` that get normalized
#   - report-bounds.jq     — find exclusive bounds that get rewritten
#   - report-collisions.jq — find property names that collide in Go
#   - report-ops.jq       — find operations to remove
#   - prune.jq            — perform normalization + pruning
#   - verify.jq           — sanity check post-pruning
#   - leftovers.jq        — diagnostics (should be empty after pruning)
#
# Each filter declares its own dependency on bad.jq via `include "bad";`,
# resolved through the -L search path. Load order no longer matters.

set -euo pipefail

export GOCACHE="${GOCACHE:-/tmp/hfhub-go-cache}"

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
SPEC_URL="${SPEC_URL:-https://huggingface.co/.well-known/openapi.json}"
PROCESSED_SPEC="openapi.processed.json"
DEVIATIONS_DOC="SPEC_DEVIATIONS.md"

JQ_FILTERS="$SCRIPT_DIR/jq"

# Check that all prerequisite tools are installed before doing any work.
check_dependencies() {
  local missing=0 tool
  for tool in "$@"; do
    command -v "$tool" >/dev/null 2>&1 || {
      echo "ERROR: prerequisite not found on PATH: ${tool}" >&2
      missing=1
    }
  done
  ((missing == 0))
}

check_dependencies curl jq awk go

pushd "$(dirname "${BASH_SOURCE[0]}")/.." >/dev/null

WORKDIR=$(mktemp -d)
trap 'popd >/dev/null; rm -rf "$WORKDIR"' EXIT

echo "==> Fetching ${SPEC_URL}"
curl -sSfl "$SPEC_URL" -o "$WORKDIR/raw.json"

echo "==> Detecting schema deviations from the raw spec"
jq -r -L "$JQ_FILTERS" -f "$JQ_FILTERS/report-props.jq" "$WORKDIR/raw.json" \
  >"$WORKDIR/removed-props.tsv"

jq -r -L "$JQ_FILTERS" -f "$JQ_FILTERS/report-items.jq" "$WORKDIR/raw.json" \
  >"$WORKDIR/normalized-items.tsv"

jq -r -L "$JQ_FILTERS" -f "$JQ_FILTERS/report-bounds.jq" "$WORKDIR/raw.json" \
  >"$WORKDIR/rewritten-bounds.tsv"

jq -r -L "$JQ_FILTERS" -f "$JQ_FILTERS/report-collisions.jq" "$WORKDIR/raw.json" \
  >"$WORKDIR/collisions.tsv"

echo "==> Normalizing and pruning the spec"
jq -L "$JQ_FILTERS" -f "$JQ_FILTERS/prune.jq" "$WORKDIR/raw.json" \
  >"$PROCESSED_SPEC"

jq -r -L "$JQ_FILTERS" -f "$JQ_FILTERS/report-ops.jq" "$PROCESSED_SPEC" \
  >"$WORKDIR/removed-ops.tsv"

echo "==> Verifying no unsupported schemas remain"
if ! jq -e -L "$JQ_FILTERS" -f "$JQ_FILTERS/verify.jq" "$PROCESSED_SPEC" >/dev/null; then
  echo "ERROR: unsupported schemas remain that cannot be pruned automatically:" >&2
  jq -r -L "$JQ_FILTERS" -f "$JQ_FILTERS/leftovers.jq" "$PROCESSED_SPEC" >&2
  echo "Remove these manually (or extend prune.jq), then re-run." >&2
  exit 1
fi

prop_count=$(grep -c . "$WORKDIR/removed-props.tsv" 2>/dev/null || true)
item_count=$(grep -c . "$WORKDIR/normalized-items.tsv" 2>/dev/null || true)
bound_count=$(grep -c . "$WORKDIR/rewritten-bounds.tsv" 2>/dev/null || true)
collision_count=$(grep -c . "$WORKDIR/collisions.tsv" 2>/dev/null || true)
op_count=$(grep -c . "$WORKDIR/removed-ops.tsv" 2>/dev/null || true)

echo "==> Writing ${DEVIATIONS_DOC} (${prop_count} properties removed, ${item_count} items normalized, ${bound_count} bound sets rewritten, ${collision_count} name collisions, ${op_count} operations removed)"

DOC_TMP="$WORKDIR/$DEVIATIONS_DOC"

# Header: unquoted delimiter so $SPEC_URL and $(date) expand.
cat >"$DOC_TMP" <<EOF
# Deviations from the upstream Hub API spec

Generated by the client build script — do not edit by hand.

- Upstream spec: ${SPEC_URL}
- Processed at: $(date -u '+%Y-%m-%d %H:%M:%SZ')
EOF

if ((prop_count == 0 && item_count == 0 && bound_count == 0 && collision_count == 0 && op_count == 0)); then
  cat >>"$DOC_TMP" <<'EOF'

No deviations this run — the upstream spec parsed cleanly.
EOF
fi

if ((bound_count > 0)); then
  # Quoted delimiter: markdown backticks would otherwise trigger command
  # substitution in an unquoted heredoc.
  cat >>"$DOC_TMP" <<'EOF'

## Rewritten exclusive bounds

These schemas use the OpenAPI 3.1 / JSON Schema 2020-12 numeric form of
`exclusiveMinimum`/`exclusiveMaximum`, which ogen's parser cannot read
(it expects the OpenAPI 3.0 boolean form). They are rewritten to the
equivalent 3.0 form: `exclusiveMinimum: N` becomes `minimum: N` +
`exclusiveMinimum: true`. This is a semantics-preserving dialect
translation — the validated value space is unchanged.

| Location | exclusiveMinimum | exclusiveMaximum |
| --- | --- | --- |
EOF
  awk -F'\t' '{ printf "| `%s` | `%s` | `%s` |\n", $1, $2, $3 }' \
    "$WORKDIR/rewritten-bounds.tsv" >>"$DOC_TMP"
fi

if ((item_count > 0)); then
  cat >>"$DOC_TMP" <<'EOF'

## Normalized `items` constraints

These schemas declare `items` as a scalar (`false` or `true`), which ogen
cannot parse. They are rewritten to the empty schema `{}` ("any element").

For `items: false` this LOOSENS the strict JSON Schema contract (which
requires an empty array). Observed upstream specs use `items: false` as an
apparent generation artifact, while real API payloads contain elements, so
the loosened form reflects actual behavior. Elements decode as generic
values rather than typed fields.

| Location | Original |
| --- | --- |
EOF
  awk -F'\t' '{ printf "| `%s` | `%s` |\n", $1, $2 }' \
    "$WORKDIR/normalized-items.tsv" >>"$DOC_TMP"
fi

if ((collision_count > 0)); then
  cat >>"$DOC_TMP" <<'EOF'

## Resolved property-name collisions

These sibling properties map to the same Go struct field after ogen's name
mangling (e.g. `id` and `_id` both become `ID`), which ogen rejects. One
property per group is kept — the non-underscore-prefixed,
lexicographically-smallest name wins; the rest are removed.

| Location | Kept | Removed |
| --- | --- | --- |
EOF
  awk -F'\t' '{ printf "| `%s` | `%s` | `%s` |\n", $1, $2, $3 }' \
    "$WORKDIR/collisions.tsv" >>"$DOC_TMP"
fi

if ((prop_count > 0)); then
  cat >>"$DOC_TMP" <<'EOF'

## Removed properties

These fields use JSON Schema constructs ogen cannot represent (multi-type
unions such as `type: [string, boolean]`). Decoding ignores unknown JSON
keys, so responses are unaffected — these struct fields simply do not exist
in the generated client. Note: if such a field is part of a request body,
the client cannot set it.

| Location | Property | Original schema |
| --- | --- | --- |
EOF
  awk -F'\t' '{
    s = $3; if (length(s) > 160) s = substr(s, 1, 160) "…";
    printf "| `%s` | `%s` | `%s` |\n", $1, $2, s
  }' "$WORKDIR/removed-props.tsv" >>"$DOC_TMP"
fi

if ((op_count > 0)); then
  cat >>"$DOC_TMP" <<'EOF'

## Removed operations

Whole endpoints dropped, either because they lack a `responses` object
(invalid OpenAPI — typically redirect/media endpoints like avatars) or
because their schemas contained constructs that could not be repaired by
removing individual properties.

| Path | Method |
| --- | --- |
EOF
  awk -F'\t' '{ printf "| `%s` | `%s` |\n", $1, $2 }' \
    "$WORKDIR/removed-ops.tsv" >>"$DOC_TMP"
fi

mv "$DOC_TMP" "$DEVIATIONS_DOC"

echo "==> Generating client with ogen"
go tool ogen --target ./ --package hfhub --clean "$PROCESSED_SPEC"
go mod tidy

echo "==> Running ogen generated tests"
go test -race ./...

echo "==> Done."
echo "    Review ${DEVIATIONS_DOC} and the diff of ${PROCESSED_SPEC} before merging."
